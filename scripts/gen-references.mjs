#!/usr/bin/env node
/**
 * Generate `references/` from the format table.
 *
 * The table is the single source of truth, and a hand-written reference is a
 * second copy of it that drifts. That drift is the chronic disease of tools like
 * this one: the validator refuses a value the documentation says is fine, and
 * nobody notices for a month.
 *
 *   node scripts/gen-references.mjs            write the files
 *   node scripts/gen-references.mjs --check    exit 1 if a file is out of date
 *
 * `--check` is the part that matters. Run it in a test so a change to the table
 * without a regenerated reference fails the build.
 */

import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

import {
  CSS_ORDER, CSS_ALLOWED, CSS_ALIASES, REJECTED_PROPERTIES, TYPE_TAGS, ATTR_BY_TYPE,
  COMMON_OPTIONAL, SHAPE_KINDS, ICON_LIBRARIES, TOKEN_GROUPS, TOKEN_GROUP_UNIT,
  ID_PATTERN, TAG_TO_TYPE, TYPE_HAS_CHILDREN, COMMON_MISTAKES,
} from "../lib/table.mjs";
import { SCHEMA_VERSION, SCHEMA_META_NAME } from "../lib/validate.mjs";
import { ICON_LIBRARY, ICONS } from "../lib/icons.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "..");
const OUT = path.join(ROOT, "references");

// -- styling ------------------------------------------------------------------

function stylingDoc() {
  const lines = [];
  lines.push("# Styling reference");
  lines.push("");
  lines.push("<!-- Generated by scripts/gen-references.mjs from lib/table.mjs. Do not edit. -->");
  lines.push("");
  lines.push(`Every element styles itself with a \`style\` attribute. These ${CSS_ORDER.length} properties are the`);
  lines.push("whole set. A property outside this list is refused by name, with the replacement named");
  lines.push("when there is one.");
  lines.push("");
  lines.push("Values are written in the canonical form, and a write reports every value it");
  lines.push("rewrote. The short version: six or eight digit lower case hex, `px` lengths with zero");
  lines.push("written `0`, `gap` and never `margin`, and longhand font properties.");
  lines.push("");
  lines.push("## The properties");
  lines.push("");
  lines.push("| Property | Accepted values |");
  lines.push("|---|---|");
  for (const name of CSS_ORDER) {
    const spec = CSS_ALLOWED[name];
    lines.push(`| \`${name}\` | ${escapePipes(spec?.hint ?? "—")} |`);
  }
  lines.push("");
  lines.push("## Value forms");
  lines.push("");
  lines.push("| Property | Kind | Notes |");
  lines.push("|---|---|---|");
  for (const name of CSS_ORDER) {
    const spec = CSS_ALLOWED[name];
    if (!spec) continue;
    lines.push(`| \`${name}\` | ${spec.kind} | ${escapePipes(valueNotes(spec))} |`);
  }
  lines.push("");
  lines.push("## Aliases");
  lines.push("");
  lines.push("An alias is accepted and rewritten. The file ends up holding the target.");
  lines.push("");
  lines.push("| Written | Becomes |");
  lines.push("|---|---|");
  for (const [from, to] of Object.entries(CSS_ALIASES)) lines.push(`| \`${from}\` | \`${to}\` |`);
  lines.push("");
  lines.push("## Refused properties");
  lines.push("");
  lines.push("Each one is refused with the reason below, so a refusal tells you what to write");
  lines.push("instead.");
  lines.push("");
  lines.push("| Property | Reason | Write instead |");
  lines.push("|---|---|---|");
  for (const [property, info] of Object.entries(REJECTED_PROPERTIES).sort((a, b) => a[0].localeCompare(b[0]))) {
    lines.push(`| \`${property}\` | ${escapePipes(info.reason)} | ${info.replacement ? `\`${escapePipes(info.replacement)}\`` : "—"} |`);
  }
  lines.push("");
  lines.push("## Custom properties");
  lines.push("");
  lines.push("A declaration whose name starts with `--` is always accepted. That is how a design");
  lines.push("carries a local value without a token for it.");
  lines.push("");
  lines.push("## Tokens");
  lines.push("");
  lines.push("Tokens are declared once, in the `<head>`:");
  lines.push("");
  lines.push("```html");
  lines.push(`<style>:root{ --color-bg:#0b0d12; ${TOKEN_GROUPS.filter((g) => TOKEN_GROUP_UNIT[g]).map((g) => `--${g}-md:16px`)[0]} }</style>`);
  lines.push("```");
  lines.push("");
  lines.push(`The group is the text before the first hyphen, and it must be one of: ${TOKEN_GROUPS.map((g) => `\`${g}\``).join(", ")}.`);
  lines.push("");
  lines.push("| Group | Unit a number carries |");
  lines.push("|---|---|");
  for (const group of TOKEN_GROUPS) {
    const unit = TOKEN_GROUP_UNIT[group];
    lines.push(`| \`${group}\` | ${unit ?? "none (a colour, a font stack, a shadow)"} |`);
  }
  lines.push("");
  lines.push("Reference a token with `var(--name)`. `export --resolve-tokens` bakes the values in");
  lines.push("instead, so the deliverable needs no token block.");
  lines.push("");
  return lines.join("\n");
}

function valueNotes(spec) {
  switch (spec.kind) {
    case "color": return "Six or eight digit hex, lower case. `transparent` is allowed. `rgb()` and `rgba()` are rewritten to hex.";
    case "length": return "`px`, `%`, `em`, `rem`, `vh`, `vw`, or a keyword such as `auto` and `fit-content`. Zero is `0`.";
    case "number": return spec.min !== undefined || spec.max !== undefined ? `Between ${spec.min ?? "−∞"} and ${spec.max ?? "∞"}.` : "Up to three decimals.";
    case "enum": return `One of: ${spec.values.map((v) => `\`${v}\``).join(", ")}.`;
    case "keyword-set": return `One of: ${spec.values.map((v) => `\`${v}\``).join(", ")}.`;
    case "flex": return "`1 1 0%` fills the main axis. A bare number becomes `n 1 0%`.";
    case "border": return "Width, style, colour, in that order however they were written.";
    case "shadow": return "`x y blur [spread] colour`, one or more separated by commas. Inner shadows are refused.";
    case "image": return "`url(\"...\")` or a `linear-gradient(...)`. The url argument is always quoted, so a `;` inside it cannot split the declaration.";
    case "font-weight": return "`400`, `500`, `600`, `700`. The words `normal`, `medium`, `semibold` and `bold` are rewritten to numbers.";
    case "line-height": return "A ratio such as `1.5`, or a length.";
    case "text": return "Taken as written.";
    default: return "—";
  }
}

// -- schema -------------------------------------------------------------------

function schemaDoc() {
  const lines = [];
  lines.push("# Element reference");
  lines.push("");
  lines.push("<!-- Generated by scripts/gen-references.mjs from lib/table.mjs. Do not edit. -->");
  lines.push("");
  lines.push("## The file");
  lines.push("");
  lines.push(`A design file is valid, self-contained HTML. It carries \`<meta name="${SCHEMA_META_NAME}" content="${SCHEMA_VERSION}">\``);
  lines.push("and exactly two `<style>` blocks, both in `<head>`:");
  lines.push("");
  lines.push("- the token block: `:root{ --color-bg:#0b0d12 }`");
  lines.push("- the page-frame block: `section[data-type=\"page\"]{ margin:0 0 24px }`");
  lines.push("");
  lines.push("Everything else is inline in a `style` attribute. One file holds many pages; a page is");
  lines.push("`<section data-type=\"page\">`.");
  lines.push("");
  lines.push("## Every element");
  lines.push("");
  lines.push("| Attribute | Required | Rule |");
  lines.push("|---|---|---|");
  lines.push(`| \`data-id\` | yes | Unique in the whole file. Matches \`${ID_PATTERN.source}\`. |`);
  lines.push("| `data-type` | yes | Must match the tag. See the table below. |");
  lines.push("");
  lines.push("Optional on any element:");
  lines.push("");
  lines.push("| Attribute | Rule |");
  lines.push("|---|---|");
  lines.push("| `data-name` | A display name. For people, and for the layer tree. |");
  lines.push("| `data-hidden` | `\"true\"` hides the element while keeping it in the file. |");
  lines.push("| `data-locked` | `\"true\"` stops the canvas moving it. It produces no CSS. |");
  lines.push("");
  lines.push("## The eight types");
  lines.push("");
  lines.push("| `data-type` | Tag | Required attributes | May contain elements |");
  lines.push("|---|---|---|---|");
  for (const [type, tags] of Object.entries(TYPE_TAGS)) {
    const contract = ATTR_BY_TYPE[type] ?? { required: [] };
    const required = contract.required.length ? contract.required.map((a) => `\`${a}\``).join(", ") : "—";
    lines.push(`| \`${type}\` | ${tags.map((t) => `\`<${t}>\``).join(" ")} | ${required} | ${TYPE_HAS_CHILDREN.has(type) ? "yes" : "no"} |`);
  }
  lines.push("");
  lines.push("Additional attributes by type:");
  lines.push("");
  lines.push("| `data-type` | Attribute | Rule |");
  lines.push("|---|---|---|");
  lines.push(`| \`page\` | \`data-canvas\` | \`"x,y"\`, the position on the canvas. |`);
  lines.push("| `page` | `data-library` | `\"true\"` marks a component library page, which `export --all` skips. |");
  lines.push(`| \`shape\` | \`data-kind\` | One of: ${SHAPE_KINDS.map((k) => `\`${k}\``).join(", ")}. |`);
  lines.push("| `icon` | `data-icon` | The glyph name. |");
  lines.push(`| \`icon\` | \`data-icon-library\` | One of: ${ICON_LIBRARIES.map((l) => `\`${l}\``).join(", ")}. |`);
  lines.push("| `instance` | `data-ref` | The `data-id` of a component. |");
  lines.push("| `instance` | `data-overrides` | JSON. Field-level patches, keyed by a descendant's `data-id`. |");
  lines.push("| `image` | `data-credit` | Attribution. Never rendered. |");
  lines.push("");
  lines.push("## A tag maps to a default type");
  lines.push("");
  lines.push("Useful when the file omits `data-type`, which is an error, so the message can name the");
  lines.push("type the tag implied.");
  lines.push("");
  lines.push("| Tag | Default `data-type` |");
  lines.push("|---|---|");
  for (const [tag, type] of Object.entries(TAG_TO_TYPE)) lines.push(`| \`<${tag}>\` | \`${type}\` |`);
  lines.push("");
  lines.push("## Icons");
  lines.push("");
  lines.push(`The built-in set is \`${ICON_LIBRARY}\` with ${ICONS.length} glyphs. An \`icon\` element holds its own geometry,`);
  lines.push("so it needs no network request and no icon font:");
  lines.push("");
  lines.push("```html");
  lines.push('<svg data-id="home__icon" data-type="icon" data-icon="shield-check" data-icon-library="lucide"');
  lines.push('     style="width:24px;height:24px;color:var(--color-ink)">');
  lines.push('  <path d="M12 2l8 4v6c0 5-8 10-8 10S4 17 4 12V6z"></path>');
  lines.push("</svg>");
  lines.push("```");
  lines.push("");
  lines.push("Everything inside an `<svg>` is the opaque layer: kept byte for byte, never indexed, never");
  lines.push("validated as a design element. An id inside an `<svg>` is an error, because nothing can");
  lines.push("address it.");
  lines.push("");
  lines.push("## Components and instances");
  lines.push("");
  lines.push("A component is a `div` with `data-type=\"component\"`. It renders exactly like a frame. An");
  lines.push("instance references it by id, and the file stores no copy:");
  lines.push("");
  lines.push("```html");
  lines.push('<div data-id="card" data-type="component" style="display:flex;gap:4px;padding:16px">');
  lines.push('  <p data-id="card__title" data-type="text" style="font-size:14px">Card</p>');
  lines.push("</div>");
  lines.push("");
  lines.push('<div data-id="home__card" data-type="instance" data-ref="card"');
  lines.push('     data-overrides=\'{"card__title":{"content":"Hi","style":"font-size:20px"}}\'></div>');
  lines.push("```");
  lines.push("");
  lines.push("Overridable fields: `content`, `style`, and any `data-*` attribute. `data-id`, `data-type`");
  lines.push("and the children are not overridable, because they are structure.");
  lines.push("");
  return lines.join("\n");
}

// -- cookbook -----------------------------------------------------------------

function cookbookDoc() {
  const lines = [];
  lines.push("# Cookbook");
  lines.push("");
  lines.push("<!-- Generated by scripts/gen-references.mjs from lib/table.mjs. Do not edit. -->");
  lines.push("");
  lines.push("The patterns that come up on every page, written the way this format wants them.");
  lines.push("");
  lines.push("## Page shell");
  lines.push("");
  lines.push("```html");
  lines.push('<section data-id="home" data-type="page" data-name="Home" data-canvas="0,0" style="width:390px;height:844px">');
  lines.push('  <div data-id="home__root" data-type="frame" style="display:flex;flex-direction:column;width:100%;height:100%;background-color:var(--color-bg)">');
  lines.push("  </div>");
  lines.push("</section>");
  lines.push("```");
  lines.push("");
  lines.push("The page owns its own size. The root fills it.");
  lines.push("");
  lines.push("## A vertical stack with spacing");
  lines.push("");
  lines.push("```html");
  lines.push('<div data-id="home__list" data-type="frame" style="display:flex;flex-direction:column;gap:12px;padding:24px">');
  lines.push("</div>");
  lines.push("```");
  lines.push("");
  lines.push("`gap` is the whole spacing system. There is no `margin`.");
  lines.push("");
  lines.push("## A row that pushes its ends apart");
  lines.push("");
  lines.push("```html");
  lines.push('<div data-id="home__bar" data-type="frame" style="display:flex;align-items:center;justify-content:space-between;height:48px;padding:0 16px;background-color:#ffffff">');
  lines.push("</div>");
  lines.push("```");
  lines.push("");
  lines.push("## Two children that split the width");
  lines.push("");
  lines.push("```html");
  lines.push('<div data-id="home__split" data-type="frame" style="display:flex;flex-direction:row;gap:8px">');
  lines.push('  <div data-id="home__left" data-type="frame" style="flex:1 1 0%;min-width:0"></div>');
  lines.push('  <div data-id="home__right" data-type="frame" style="flex:1 1 0%;min-width:0"></div>');
  lines.push("</div>");
  lines.push("```");
  lines.push("");
  lines.push("`flex:1 1 0%` plus `min-width:0` is the one spelled way to fill a row. Without");
  lines.push("`min-width:0`, a long word pushes the child past its share.");
  lines.push("");
  lines.push("## A card");
  lines.push("");
  lines.push("```html");
  lines.push('<div data-id="home__card" data-type="frame" style="display:flex;flex-direction:column;gap:8px;padding:16px;background-color:#ffffff;border:1px solid #e5e7eb;border-radius:12px;box-shadow:0 1px 2px #00000014">');
  lines.push("</div>");
  lines.push("```");
  lines.push("");
  lines.push("## Text sizes");
  lines.push("");
  lines.push("| Role | Style |");
  lines.push("|---|---|");
  lines.push("| Display | `font-size:44px;font-weight:700;line-height:1.1` |");
  lines.push("| Title | `font-size:24px;font-weight:600;line-height:1.25` |");
  lines.push("| Body | `font-size:16px;font-weight:400;line-height:1.5` |");
  lines.push("| Label | `font-size:14px;font-weight:500;line-height:1.4` |");
  lines.push("| Caption | `font-size:12px;font-weight:400;line-height:1.4;color:#6b7280` |");
  lines.push("");
  lines.push("## A pill");
  lines.push("");
  lines.push("```html");
  lines.push('<p data-id="home__tag" data-type="text" style="font-size:12px;font-weight:500;padding:4px 10px;background-color:#f3f4f6;border-radius:9999px;color:#374151">New</p>');
  lines.push("```");
  lines.push("");
  lines.push("`border-radius:9999px` is the pill. A circle is `border-radius:50%` on a square box.");
  lines.push("");
  lines.push("## An image that fills its box");
  lines.push("");
  lines.push("```html");
  lines.push('<img data-id="home__photo" data-type="image" src="photo.jpg" alt="A room" style="width:100%;height:200px;object-fit:cover;border-radius:12px">');
  lines.push("```");
  lines.push("");
  lines.push("`alt` is required. `alt=\"\"` marks a decorative image, and that is different from");
  lines.push("omitting it.");
  lines.push("");
  lines.push("## A background image");
  lines.push("");
  lines.push("```html");
  lines.push('<div data-id="home__hero" data-type="frame" style="height:240px;background-image:url(&quot;hero.jpg&quot;);background-size:cover;background-position:center"></div>');
  lines.push("```");
  lines.push("");
  lines.push("## A gradient scrim");
  lines.push("");
  lines.push("```html");
  lines.push('<div data-id="home__scrim" data-type="frame" style="height:120px;background-image:linear-gradient(180deg,#ffffff00,#00000099)"></div>');
  lines.push("```");
  lines.push("");
  lines.push("Only linear gradients. A radial or a mesh gradient is refused, with the reason named.");
  lines.push("");
  lines.push("## The most common refusals");
  lines.push("");
  lines.push("| Written | Refused because | Write this |");
  lines.push("|---|---|---|");
  for (const mistake of COMMON_MISTAKES.slice(0, 12)) {
    lines.push(`| \`${mistake.property}\` | ${escapePipes(mistake.reason)} | ${mistake.replacement ? `\`${escapePipes(mistake.replacement)}\`` : "remove it"} |`);
  }
  lines.push("");
  return lines.join("\n");
}

function escapePipes(text) {
  return String(text ?? "").replace(/\|/g, "\\|");
}

// -- write --------------------------------------------------------------------

const FILES = {
  "styling.md": stylingDoc(),
  "schema.md": schemaDoc(),
  "cookbook.md": cookbookDoc(),
};

const check = process.argv.includes("--check");
let stale = 0;

if (!check) fs.mkdirSync(OUT, { recursive: true });

for (const [name, content] of Object.entries(FILES)) {
  const target = path.join(OUT, name);
  const body = content.endsWith("\n") ? content : `${content}\n`;
  if (check) {
    const existing = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
    if (existing !== body) {
      console.error(`stale     references/${name} — run: node scripts/gen-references.mjs`);
      stale += 1;
    } else {
      console.log(`ok        references/${name}`);
    }
    continue;
  }
  fs.writeFileSync(target, body, "utf8");
  console.log(`wrote     references/${name} (${body.length} bytes)`);
}

if (check && stale > 0) process.exitCode = 1;
